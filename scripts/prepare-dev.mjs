import { spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
function git(args, snapshot) {
  const env = { ...process.env };
  // Hooks and Git wrappers can export these for their own repository.
  // Keep tool/user configuration, but never reuse another repository's state.
  const repositoryVariables = new Set([
    'GIT_DIR', 'GIT_WORK_TREE', 'GIT_IMPLICIT_WORK_TREE', 'GIT_COMMON_DIR',
    'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES',
    'GIT_NAMESPACE', 'GIT_PREFIX', 'GIT_INTERNAL_SUPER_PREFIX',
    'GIT_SHALLOW_FILE', 'GIT_GRAFT_FILE', 'GIT_REPLACE_REF_BASE',
  ]);
  for (const key of Object.keys(env)) {
    if (repositoryVariables.has(key.toUpperCase())) delete env[key];
  }
  const result = spawnSync('git', [
    '--git-dir', path.join(snapshot, '.git'), '--work-tree', snapshot, ...args,
  ], {
    cwd: snapshot, encoding: 'utf8',
    // Keep the generated artifact reproducible and separate from user identity.
    env: { ...env, GIT_AUTHOR_NAME: 'Local Grammar Build',
      GIT_AUTHOR_EMAIL: 'grammar-build@localhost', GIT_COMMITTER_NAME: 'Local Grammar Build',
      GIT_COMMITTER_EMAIL: 'grammar-build@localhost',
      GIT_AUTHOR_DATE: '2000-01-01T00:00:00Z', GIT_COMMITTER_DATE: '2000-01-01T00:00:00Z' },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || `git exited ${result.status}`);
  return result.stdout.trim();
}

export async function prepareDev(projectRoot = root) {
  projectRoot = path.resolve(projectRoot);
  const cache = path.join(projectRoot, '.build');
  const snapshot = path.join(cache, 'grammar-repository');
  const devExtension = path.join(cache, 'dev-extension');
  // These two copies are generated by this script and must not retain deleted files.
  for (const destination of [snapshot, devExtension]) {
    if (path.dirname(destination) !== cache) throw new Error('Development copy is outside the build directory');
    await rm(destination, { recursive: true, force: true });
  }
  await mkdir(snapshot, { recursive: true });
  await cp(path.join(projectRoot, 'tree-sitter-ignition', 'src'), path.join(snapshot, 'src'), { recursive: true });
  await cp(path.join(projectRoot, 'tree-sitter-ignition', 'grammar.js'), path.join(snapshot, 'grammar.js'));
  await cp(path.join(projectRoot, 'LICENSE'), path.join(snapshot, 'LICENSE'));
  await cp(path.join(projectRoot, 'NOTICE.md'), path.join(snapshot, 'NOTICE.md'));
  await cp(path.join(projectRoot, 'licenses'), path.join(snapshot, 'licenses'), { recursive: true });
  git(['init', '--quiet'], snapshot);
  git(['-c', 'core.autocrlf=false', 'add', 'src', 'grammar.js', 'LICENSE', 'NOTICE.md', 'licenses'], snapshot);
  const tree = git(['write-tree'], snapshot);
  // commit-tree creates only a build snapshot; no source project is committed.
  const revision = git(['commit-tree', tree, '-m', 'build: snapshot ignition grammar'], snapshot);
  git(['update-ref', 'refs/heads/main', revision], snapshot);
  const template = await readFile(path.join(projectRoot, 'extension.template.toml'), 'utf8');
  const manifest = template.replace('{{GRAMMAR_REPOSITORY}}', () => pathToFileURL(snapshot).href)
    .replace('{{GRAMMAR_REVISION}}', () => revision);
  await mkdir(devExtension, { recursive: true });
  await cp(path.join(projectRoot, 'languages'), path.join(devExtension, 'languages'), { recursive: true });
  await cp(path.join(projectRoot, 'LICENSE'), path.join(devExtension, 'LICENSE'));
  await cp(path.join(projectRoot, 'NOTICE.md'), path.join(devExtension, 'NOTICE.md'));
  await cp(path.join(projectRoot, 'licenses'), path.join(devExtension, 'licenses'), { recursive: true });
  await writeFile(path.join(devExtension, 'extension.toml'), manifest);
  console.log('Prepared .build/dev-extension with a local grammar snapshot.');
  console.log(`In Zed: Extensions → Install Dev Extension → ${devExtension}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  prepareDev().catch(error => { console.error(error.message); process.exitCode = 1; });
}
